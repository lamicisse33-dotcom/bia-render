import assert from "node:assert/strict";
import {lireFluxConversation} from "../lib/flux-conversation.js";
const encoder=new TextEncoder();
let controller;
const body=new ReadableStream({start(c){controller=c;}});
let emitted="", voiceStarted=false;
const pending=lireFluxConversation(new Response(body),t=>{emitted+=t;if(emitted.includes("."))voiceStarted=true;});
controller.enqueue(encoder.encode('data: {"model":"gpt-oss-120b","choices":[{"index":0,"delta":{"content":"Bonjour, je suis contente de te parler."}}]}\r\n\r\n'));
await new Promise(r=>setTimeout(r,0));
assert.equal(voiceStarted,true,"First phrase can start TTS while the model stream is still open");
let settled=false;pending.then(()=>settled=true);
await new Promise(r=>setTimeout(r,0));assert.equal(settled,false);
const suite=encoder.encode('data: {"choices":[{"delta":{"content":" Voici la suite en français."}}]}\n\ndata: {"choices":[{"delta":{},"finish_reason":"stop"}],"usage":{"prompt_tokens":12,"completion_tokens":9}}\n\ndata: [DONE]\n\n');
for(let i=0;i<suite.length;i+=3)controller.enqueue(suite.slice(i,i+3));
controller.close();
const final=await pending;
assert.equal(final.choices[0].message.content,emitted);
assert.equal(final.usage.completion_tokens,9);
assert.equal(final.model,"gpt-oss-120b");
assert.equal((emitted.match(/Bonjour/g)||[]).length,1);
await assert.rejects(()=>lireFluxConversation(new Response('data: {"choices":[{"delta":{"content":"Incomplet"}}]}\n\n'),()=>{}),/interrompu/);
await assert.rejects(()=>lireFluxConversation(new Response('data: {"error":{"message":"error"}}\n\n'),()=>{}),/échoué/);
console.log("Streaming overlap, UTF-8 fragmentation, usage, failure and no-duplication tests passed");
